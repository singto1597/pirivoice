// ⚠️ **ทั้งไฟล์นี้ห้ามแตะ DOM** — รับ/คืนค่าเป็นข้อมูลล้วน ⇒ เทสต์ได้ใน jsdom
//    (การวาด SVG เป็น *สตริง* ไม่ใช่การสั่งเบราว์เซอร์วาด) ส่วนกล้องอยู่ในคอมโพเนนต์

import qrcode from 'qrcode-generator'

/**
 * 🛡️ **ต้องตั้งบรรทัดนี้ก่อนเรียก `make()` ครั้งแรกเสมอ** — ค่า default ของไลบรารีคือ
 * `stringToBytesFuncs['default']` ซึ่งแปลงอักขระเป็นไบต์ด้วย `charCodeAt(i) & 0xff`
 * ⇒ **ข้อความไทยถูกตัดทิ้งเงียบ ๆ** ตัวละ 1 ไบต์ แล้วผู้สแกนจะได้ตัวอักษรมั่วกลับมา
 * (ทดสอบจริง: `"กิจกรรมปลูกป่า"` → `"4\b##!…"` โดยไม่มี error ใด ๆ)
 *
 * ⚠️ **วันนี้ยังไม่ระเบิดเพราะเนื้อใน QR ของเรามีแต่ ASCII** (โทเคน `PIRI-EVT1:…` กับ URL)
 *    แต่ `QrCode.vue` เป็นคอมโพเนนต์กลางที่รับข้อความอะไรก็ได้ ⇒ ดักไว้ตรงนี้ที่เดียว
 *    ถูกกว่าไปหวังว่าทุกที่ที่เรียกจะส่งแต่ ASCII (และความเสียหายเงียบแบบนี้แพงมาก:
 *    QR ที่พิมพ์ติดหน้าโรงเรียนแล้วสแกนได้ตัวมั่ว คือวันที่ต้องพิมพ์ใหม่ทั้งชุด)
 *
 * ASCII ไม่กระทบ (UTF-8 ของ ASCII = ไบต์เดิม) ⇒ ไม่มีอะไรแลกมา
 *
 * ⚠️⚠️ **ห้ามใช้ `qrcode.stringToBytesFuncs['UTF-8']` ของไลบรารี** — ฟังก์ชันนั้น
 *    **มีอยู่เฉพาะในบิลด์ CJS (`dist/qrcode.js`) เท่านั้น** ส่วนบิลด์ ESM (`dist/qrcode.mjs`)
 *    ไม่มี `stringToBytesFuncs` เลย และ **Vite/เบราว์เซอร์โหลดตัว ESM** (`exports.import`)
 *    ⇒ โค้ดที่อ้าง `stringToBytesFuncs` จะเงียบ/พังในเบราว์เซอร์ ทั้งที่ลองด้วย `require()`
 *    ใน Node แล้วผ่าน (กับดักนี้เจอจริงในรอบ D2)
 *    ⇒ **เขียน UTF-8 เองด้วย `TextEncoder`** — ได้ผลเหมือนกันทั้งสองบิลด์ และเหลือทางเดียว
 *
 * ⚠️ ไลบรารีอ่านค่านี้ **ตอน `make()` ไม่ใช่ตอน import** (`qrcode.stringToBytes(data)`)
 *    ⇒ การเขียนทับตรงนี้มีผลจริง · เทสต์ round-trip ข้อความไทยคือด่านที่ยืนยันข้อนี้
 */
qrcode.stringToBytes = (s: string): number[] => Array.from(new TextEncoder().encode(s))

/**
 * ระดับแก้ไขข้อผิดพลาด — **`M` (15%) เป็นค่าที่ตั้งใจ ไม่ใช่ค่า default**
 *
 * QR มี 4 ระดับ: L 7% · **M 15%** · Q 25% · H 30% — ยิ่งสูงยิ่งทน แต่โค้ดก็ยิ่งใหญ่ขึ้น
 * (โมดูลมากขึ้น ⇒ แต่ละจุดเล็กลงเมื่อขนาดจอเท่าเดิม)
 *
 * เลือก M เพราะบริบทการใช้งานจริงคือ **จอมือถือที่อาจมีรอยนิ้ว/แสงสะท้อน/หน้าจอสกปรก**
 * ⇒ ต้องการเผื่อความเสียหาย แต่ยังไม่ถึงขั้นยอมแลกขนาดให้ H
 * (H จะทำให้ QR ใหญ่ขึ้น ~30% ซึ่งบนจอเล็กหมายถึงจุดเล็กลง = สแกนยากขึ้น — ได้ไม่คุ้มเสีย)
 */
const EC_LEVEL = 'M'

/** ขนาดต่อ 1 โมดูล (px) และขอบว่าง — ค่าที่ใช้กับโหมด bitmap เท่านั้น (SVG ยืดหยุ่นตาม viewBox) */
const CELL_SIZE = 4
const MARGIN = 4

/**
 * ข้อความยาวสุดที่ยอมรับ — กันการเอา QR ไปใช้วาดสตริงยักษ์โดยไม่ตั้งใจ (ไม่ใช่ด่านความปลอดภัย)
 *
 * ⚠️ **export เพื่อให้เทสต์ใช้ค่าจริง** ไม่ใช่คัดลอก `1000` ไปเขียนซ้ำในเทสต์
 *    (คัดลอกแล้ววันหน้าขยับเพดาน เทสต์จะยังผ่านด้วยเลขเก่า = เทสต์ที่โกหก)
 */
export const QR_MAX_LENGTH = 1000

/**
 * สร้าง QR เป็น **data URL ของ SVG** — ใช้กับ `<img :src>` ได้ตรง ๆ
 *
 * ⭐ **ทำไม SVG ไม่ใช่ GIF/PNG** (`createDataURL()` ของไลบรารีคืน GIF):
 *    ภาพ QR ต้อง **คมทุกขนาด** — บัตรเช็คอินถูกย่อในจอมือถือ และ QR เชิญเข้าร่วม (4.4)
 *    ถูก **พิมพ์ติดหน้าโรงเรียน** ⇒ raster ที่ถูกขยายจะเบลอตรงมุมจุด ซึ่งเป็นส่วนที่ตัวอ่าน
 *    ใช้หาตำแหน่ง (finder pattern) ⇒ เบลอ = สแกนไม่ติด
 *
 * ⭐ `scalable: true` ⇒ SVG ออกมาเป็น `viewBox` ล้วน ไม่มี width/height ตายตัว
 *    ⇒ ยืดหดตาม container ได้โดยไม่ต้องรู้ขนาดล่วงหน้า (และคมทุกระดับซูม)
 *
 * ⚠️ **`btoa` ใช้ได้เพราะ SVG ที่ไลบรารีสร้างเป็น ASCII ล้วน** — ถ้าวันหน้าเปลี่ยนไปฝัง
 *    ข้อความไทย/อีโมจิลงใน SVG ตรง ๆ ฟังก์ชันนี้จะโยน `InvalidCharacterError`
 *    (ผู้เรียกต้องมี fallback — ดู `QrCode.vue`) ⇒ ห่อ try/catch ไว้ที่ผู้เรียก ไม่ใช่ที่นี่
 */
export function qrSvgDataUrl(text: string): string {
  if (!text) throw new Error('ไม่มีข้อมูลให้สร้างคิวอาร์')
  if (text.length > QR_MAX_LENGTH) throw new Error('ข้อมูลยาวเกินกว่าจะสร้างคิวอาร์ได้')

  // typeNumber 0 = ให้ไลบรารีเลือกขนาด (version) ที่พอดีกับข้อมูลเอง
  const qr = qrcode(0, EC_LEVEL)
  qr.addData(text)
  qr.make()

  const svg = qr.createSvgTag({ cellSize: CELL_SIZE, margin: MARGIN, scalable: true })
  return `data:image/svg+xml;base64,${btoa(svg)}`
}
