import type { CheckInResult } from '@/types/event'

/**
 * อ่าน QR ทุกกี่มิลลิวินาที — ไม่ใช้อ่านทุกเฟรม
 *
 * `jsQR` ใช้เวลา ~10–20 ms ต่อเฟรมบนมือถือรุ่นกลาง ⇒ อ่าน 60 fps จะกิน CPU จนเครื่องร้อน
 * และเฟรมก็ไม่ต่างกันเลยใน 1/60 วินาที · 6–7 ครั้ง/วินาที ยังรู้สึก "ติดทันที" สำหรับคนยื่นบัตร
 */
export const SCAN_INTERVAL_MS = 150

/**
 * ระยะห่างขั้นต่ำที่จะยอมรับ **บัตรใบเดิม** อีกครั้ง
 *
 * สั้นไป: ยิงซ้ำรัว · ยาวไป: คนที่สแกนซ้ำโดยตั้งใจ (เช่นสภาไม่เห็นชื่อรอบแรก) ต้องรอนาน
 * 3 วินาที = อ่านชื่อ + มองหน้า + ปล่อยคนเข้าเสร็จพอดี
 *
 * ⚠️ มีผลกับ **บัตรใบเดิมติดกัน** เท่านั้น — บัตรคนถัดไป (โทเคนต่างกัน) ผ่านทันที
 *    ซึ่งเป็นเรื่องปกติที่สุดของงานจริง (คิวคนยื่นบัตรต่อกัน)
 */
export const SCAN_COOLDOWN_MS = 3000

export interface ScanGate {
  /**
   * ขออนุญาตประมวลผล **โทเคนจากเฟรมกล้อง** — `true` = ส่งไปเช็คอินได้ (ประตูถูกล็อกแล้ว)
   * ต้องเรียก `finish()` เสมอหลังจบคำขอ ไม่งั้นประตูค้างล็อก
   */
  beginFrame(token: string, now: number): boolean
  /**
   * ขออนุญาตประมวลผล **โทเคนที่สภาป้อนเอง** — กันแค่การยิงซ้อน
   *
   * ⚠️ **ไม่ใช้ cooldown ของกล้อง** เพราะการพิมพ์/วางรหัสเป็นการกระทำโดยเจตนาของคน
   *    ไม่ใช่ผลข้างเคียงของการที่บัตรค้างอยู่ในกรอบ · ถ้าเอา cooldown มาคุมด้วย
   *    สภาที่กดส่งซ้ำเพราะ "เมื่อกี้ไม่ขึ้นอะไร" จะเจอ "เงียบ" อีกครั้งโดยไม่รู้สาเหตุ
   *    (การส่งซ้ำโทเคนเดิมไม่เป็นอันตรายอยู่แล้ว — backend ตอบ `already_checked_in`)
   */
  beginManual(token: string, now: number): boolean
  /** ปลดล็อกประตูหลังคำขอจบ (สำเร็จหรือล้มเหลวก็ต้องเรียก) */
  finish(): void
  /** ล้างความจำทั้งหมด — ใช้ตอนกด "สแกนต่อ" ไม่ใช่ตอนจบคำขอ */
  reset(): void
}

/**
 * ประตูกันสแกนซ้ำ — สองเงื่อนไขคนละเหตุผล:
 *
 * 1. **กำลังยิงคำขออยู่** (`busy`) — กันไม่ให้เฟรมที่ตามมาในอีก 150 ms ยิงซ้อน
 *    ⇒ สแกนครั้งเดียวได้ผลลัพธ์เดียวเสมอ ไม่ใช่สองใบใน log
 * 2. **บัตรใบเดิมภายใน cooldown** — กรณีที่พบบ่อยจริง: สภาถือกล้องค้างไว้ระหว่างคุยกับเด็ก
 *    ⇒ บัตรยังอยู่ในกรอบ แต่ไม่ควรถูกนับใหม่
 *
 * ⚠️ **การกดสแกนซ้ำโดยเจตนายังต้องได้ผล** (หลังพ้น cooldown) — ไม่ใช่ปฏิเสธไปเลย
 *    เพราะถ้าสภาสงสัยว่า "เมื่อกี้ติดไหม" การสแกนซ้ำคือวิธีตรวจที่ตรงที่สุด
 *    และ backend ตอบ `already_checked_in` มาให้แสดงได้โดยไม่เขียนทับเวลาเดิม
 */
export function createScanGate(cooldownMs: number = SCAN_COOLDOWN_MS): ScanGate {
  let lastToken: string | null = null
  let lastAt = 0
  let busy = false

  function begin(token: string, now: number, cooldown: boolean): boolean {
    if (busy) return false
    if (cooldown && token === lastToken && now - lastAt < cooldownMs) return false
    busy = true
    lastToken = token
    lastAt = now
    return true
  }

  return {
    beginFrame(token: string, now: number): boolean {
      return begin(token, now, true)
    },

    beginManual(token: string, now: number): boolean {
      return begin(token, now, false)
    },

    finish(): void {
      busy = false
    },

    reset(): void {
      lastToken = null
      lastAt = 0
      busy = false
    },
  }
}

/** สี/ข้อความของแถบผลลัพธ์หลังเช็คอินหนึ่งครั้ง */
export interface CheckInBanner {
  /**
   * `ok` = เช็คอินใหม่สำเร็จ · `again` = คนนี้เช็คอินไปแล้ว (ไม่ใช่ error)
   * สองอันนี้ต้องดูต่างกันชัด ๆ เพราะสภาต้องแยกออกว่า "เพิ่งนับให้" หรือ "นับไปแล้ว"
   */
  tone: 'ok' | 'again'
  /** ข้อความบรรทัดแรก — บอกว่าเกิดอะไรขึ้น */
  title: string
  /** ⭐ ชื่อคน — ตัวที่สภาต้อง **อ่านแล้วเทียบกับหน้าคนตรงหน้า** (หัวใจของทั้งฟีเจอร์) */
  name: string
  /**
   * เวลาที่เช็คอิน (ISO) — ผู้เรียกจัดรูปแบบเอง
   * ⚠️ โมดูลนี้ **ไม่แตะ locale/เขตเวลา** โดยเจตนา ⇒ เทสต์ไม่ผูกกับ TZ ของเครื่องที่รัน
   */
  checkedInAt: string | null
}

/**
 * แปลงผลจาก API → สิ่งที่โชว์บนแถบ
 *
 * ⚠️ **ผู้ใช้ที่ไม่มีชื่อ** (`user_name === null` — ผู้ใช้ถูกลบไปแล้ว) ต้องมีข้อความสำรอง
 *    ไม่ใช่ปล่อยว่าง: สภาต้องเห็นว่า "มีคนถูกเช็คอิน" แม้ระบบไม่มีชื่อให้
 *    ⇒ โชว์รหัสผู้ใช้แทน ซึ่งตามรหัสกลับไปหาคนได้จริง
 */
export function checkInBanner(result: CheckInResult): CheckInBanner {
  const again = result.already_checked_in
  return {
    tone: again ? 'again' : 'ok',
    title: again ? 'คนนี้เช็คอินไปแล้วก่อนหน้านี้' : 'เช็คอินสำเร็จ',
    name: result.user_name ?? `ผู้ใช้ #${result.user_id}`,
    checkedInAt: result.checked_in_at,
  }
}
