import { describe, it, expect } from 'vitest'
import { closingLabel, seatsWarning, registrationChip } from '@/types/event'
import { remainingLabel } from '@/types/home'

/**
 * ⏳ กิจกรรมใกล้ปิดรับในหน้าแรก (4.5) — กติกาการแสดงผล
 *
 * ⭐ เทสต์ชุดนี้กำหนด `now` เอง **ทุกตัว** — ห้ามพึ่งเวลาจริง เพราะเทสต์ที่จะล้ม
 *    เฉพาะช่วงเที่ยงคืน/สิ้นเดือนคือเทสต์ที่แย่กว่าไม่มีเทสต์ (คนจะปิดมันทิ้ง)
 *    ⇒ `closingLabel(iso, now)` จึงรับ `now` เข้ามา (ดู docstring ของฟังก์ชัน)
 */

/** สร้าง ISO ที่ต้องการ โดยอ้างจากเวลาไทย (+07:00) ตรง ๆ เพื่อไม่ให้เทสต์ผูกกับ TZ เครื่องรัน */
function bkk(iso: string): Date {
  return new Date(iso)
}

describe('closingLabel — ป้ายบอกว่าอีกนานแค่ไหนจะปิดรับ', () => {
  it('ปิดพรุ่งนี้ (ห่าง ~2 ชม. แต่ข้ามวันตามปฏิทินไทย)', () => {
    // ⭐ นี่คือเคสที่ทำให้ต้องนับเป็น "วันตามปฏิทิน" ไม่ใช่ diff/24ชม.
    // 23:00 วันนี้ → ปิด 01:00 พรุ่งนี้ = ห่าง 2 ชม. แต่นักเรียนอ่านว่า "พรุ่งนี้"
    expect(closingLabel('2026-10-01T01:00:00+07:00', bkk('2026-09-30T23:00:00+07:00'))).toBe(
      'ปิดรับพรุ่งนี้',
    )
  })

  it('ปิดวันนี้ — บอกจำนวนชั่วโมงที่เหลือด้วย (ปัดลง ไม่ให้เกินจริง)', () => {
    // 09:00 → 12:30 = 3.5 ชม. ⇒ ปัดลงเป็น 3 (บอก "4 ชม." จะทำให้คนเลื่อนไปทำอย่างอื่นแล้วพลาด)
    expect(closingLabel('2026-09-30T12:30:00+07:00', bkk('2026-09-30T09:00:00+07:00'))).toBe(
      'ปิดรับวันนี้ · เหลืออีก 3 ชม.',
    )
  })

  it('ปิดวันนี้ เหลือไม่ถึงชั่วโมง ⇒ ต้องขึ้น 1 ชม. ไม่ใช่ 0 ชม.', () => {
    // ถ้าปัดลงตรง ๆ จะได้ 0 ⇒ "เหลืออีก 0 ชม." อ่านแล้วเหมือนหมดเขตแล้วทั้งที่ยังสมัครได้
    expect(closingLabel('2026-09-30T09:45:00+07:00', bkk('2026-09-30T09:00:00+07:00'))).toBe(
      'ปิดรับวันนี้ · เหลืออีก 1 ชม.',
    )
  })

  it('ปิดอีก 5 วัน', () => {
    expect(closingLabel('2026-10-05T10:00:00+07:00', bkk('2026-09-30T10:00:00+07:00'))).toBe(
      'ปิดรับในอีก 5 วัน',
    )
  })

  it('★ ผ่านไปแล้ว ⇒ "ปิดรับแล้ว" (ไม่ใช่ค่าติดลบ)', () => {
    // เกิดได้จริง: เปิดหน้าแรกค้างไว้ข้ามกำหนด · นาฬิกาเครื่องผู้ใช้เร็วไป
    // ⇒ ถ้าไม่กัน จะขึ้น "ปิดรับในอีก -2 วัน" ซึ่งอ่านไม่รู้เรื่อง
    expect(closingLabel('2026-09-29T10:00:00+07:00', bkk('2026-09-30T10:00:00+07:00'))).toBe(
      'ปิดรับแล้ว',
    )
    expect(closingLabel('2026-09-30T10:00:00+07:00', bkk('2026-09-30T10:00:00+07:00'))).toBe(
      'ปิดรับแล้ว',
    )
  })

  it('★ ค่าเวลาเพี้ยน ⇒ คืนสตริงว่าง ไม่โยน (ป้ายหายดีกว่าจอขาว)', () => {
    // `new Date('มะรืน')` ได้ Invalid Date ⇒ `getTime()` เป็น NaN
    // ถ้าปล่อยผ่านไปถึง Intl/toLocaleString ที่ไหนสักแห่ง มันจะ **โยน** แล้วทั้งหน้าไม่เรนเดอร์
    expect(closingLabel('ไม่ใช่วันที่', bkk('2026-09-30T10:00:00+07:00'))).toBe('')
    expect(closingLabel('', bkk('2026-09-30T10:00:00+07:00'))).toBe('')
  })

  it('★ ไม่ผูกกับ timezone ของเครื่องรันเทสต์ — เทียบ 2 instant ที่เป็นวันไทยต่างกัน', () => {
    // 2026-09-30T16:50Z = 23:50 น. ไทย (วันไทย = 30 ก.ย.)
    // 2026-09-30T17:10Z = 00:10 น. ไทย (วันไทย = 1 ต.ค.) → ต่างกัน 1 วันไทย ทั้งที่ห่าง 20 นาที
    expect(closingLabel('2026-09-30T17:10:00Z', bkk('2026-09-30T16:50:00Z'))).toBe('ปิดรับพรุ่งนี้')
  })
})

describe('seatsWarning — เตือนเฉพาะเมื่อที่นั่งเป็นเรื่องด่วน', () => {
  it('★ null (ไม่จำกัด) ⇒ ต้องไม่มีป้ายเลย ไม่ใช่ "เหลือ 0 ที่"', () => {
    // 🚨 กับดักคลาสสิก: `null <= 3` เป็น true ใน JS ⇒ เขียน `seats <= 3` ลอย ๆ
    //    จะขึ้น "เหลืออีก 3 ที่" (หรือ "เต็มแล้ว" ถ้าเทียบ <= 0) ทั้งที่ไม่จำกัดจำนวน
    expect(seatsWarning(null)).toBeNull()
  })

  it('0 ⇒ "เต็มแล้ว"', () => {
    expect(seatsWarning(0)).toBe('เต็มแล้ว — สมัครได้แต่จะได้คิวสำรอง')
  })

  it('เหลือน้อย (1–3) ⇒ บอกจำนวน — สร้างความเร่งด่วน', () => {
    expect(seatsWarning(1)).toBe('เหลืออีก 1 ที่')
    expect(seatsWarning(3)).toBe('เหลืออีก 3 ที่')
  })

  it('เหลือเยอะ (4+) ⇒ ไม่มีป้าย — ไม่ใช่ข้อมูลที่ต้องตัดสินใจอะไร', () => {
    expect(seatsWarning(4)).toBeNull()
    expect(seatsWarning(100)).toBeNull()
  })
})

describe('registrationChip — ฉันเกี่ยวข้องกับกิจกรรมนี้แล้วหรือยัง', () => {
  it('สมัครแล้ว / เช็คอินแล้ว ได้ป้ายของตัวเอง', () => {
    expect(registrationChip('registered')).toBe('สมัครแล้ว')
    expect(registrationChip('checked_in')).toBe('เช็คอินแล้ว')
  })

  it('★ waitlisted ต้องไม่ขึ้น "สมัครแล้ว" — ยังไม่มีที่นั่ง', () => {
    // ถ้าขึ้น "สมัครแล้ว" คนที่รอคิวจะไม่ไปดูว่าตัวเองได้ที่นั่งหรือยัง
    expect(registrationChip('waitlisted')).toBe('อยู่ในคิวสำรอง')
    expect(registrationChip('waitlisted')).not.toBe('สมัครแล้ว')
  })

  it('★ null ⇒ คืน null (= ยังไม่สมัคร ⇒ จอต้องแสดง *ปุ่มสมัคร*)', () => {
    // `null` ไม่ใช่ `''` โดยเจตนา — เทมเพลตเขียน `v-if="registrationChip(...)"` ตรง ๆ ได้
    expect(registrationChip(null)).toBeNull()
  })

  it('★ "cancelled" ต้องไม่มีเคส — backend แปลงเป็น null ให้แล้ว', () => {
    // ถ้ามีคน "เพิ่มความสมบูรณ์" ด้วยการใส่ `if (status === 'cancelled')` ที่นี่
    // มันจะไม่มีวันทำงาน (ค่าไม่เคยหลุดมาถึง) และทำให้นักอ่านเข้าใจผิดว่ามีทางนั้น
    // ⇒ เทสต์นี้ล็อกพฤติกรรมที่ถูกต้องไว้: มันต้องตกไปที่ null เหมือน "ยังไม่สมัคร"
    expect(registrationChip('cancelled')).toBeNull()
  })

  it('ค่าที่ไม่รู้จัก ⇒ null ไม่ใช่โยน (backend ใหม่อาจเพิ่มสถานะ)', () => {
    expect(registrationChip('something_new')).toBeNull()
  })
})

describe('remainingLabel — ใช้ร่วมกับการ์ดใหม่ได้เหมือนคิวเดิม', () => {
  it('บอก "และอีก N กิจกรรม"', () => {
    expect(remainingLabel(8, 5, 'กิจกรรม')).toBe('และอีก 3 กิจกรรม')
  })

  it('ไม่เหลือ ⇒ null', () => {
    expect(remainingLabel(5, 5, 'กิจกรรม')).toBeNull()
  })
})
