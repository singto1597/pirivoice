<script setup lang="ts">
import type { RouteLocationRaw } from 'vue-router'
import AppButton from '@/components/ui/AppButton.vue'

/**
 * ➖ "บล็อกนี้ว่าง" แบบบรรทัดเดียว — พี่น้องของ `AppEmptyState`
 *
 * **ทำไมต้องมี:** `AppEmptyState` เป็น *คอลัมน์จัดกลาง* (วงกลมไอคอน 48–64dp + ชื่อ +
 * คำอธิบาย + ปุ่ม) ซึ่งเหมาะกับ **ทั้งหน้า** ที่ว่าง แต่หน้าแรกมีบล็อกที่ว่าง *เป็นปกติ*
 * หลายบล็อก — ผู้ใช้ที่ยังไม่เคยแจ้งเรื่องเลยจะเห็น "ความว่าง" สี่ก้อน ก้อนละ ~250dp
 * รวมกันเกินหนึ่งจอครึ่ง ซึ่งเขา **ไม่เคยอ่าน** เพราะไม่มีอะไรให้อ่าน
 * ⇒ บล็อกที่ว่างจึงเหลือแถวเดียว ~44dp ที่ยังบอกว่า *"ตรวจแล้ว ไม่มีอะไรค้าง"*
 *
 * 🔴 **ยุบ ไม่ใช่ ซ่อน** — ต่างจากบล็อกโหวต/กิจกรรม/ประกาศในหน้าแรกที่ *ซ่อนทั้งบล็อก*
 *    เมื่อว่าง (ดูคอมเมนต์ใน `Home.vue`) ทั้งสองแบบถูกในบริบทของมัน:
 *    · บล็อกที่ซ่อน = *ของที่ต้องทำ* ⇒ ไม่มีก็ไม่ต้องมีบล็อก (การหายไปคือคำตอบ)
 *    · บล็อกที่ยุบ = *ของของฉัน* ⇒ "เคลียร์แล้ว" เป็น**ข้อมูล**ที่ผู้ใช้อยากรู้
 *      (โดยเฉพาะกล่อง "รอฉันตอบ" ของผู้รับเรื่อง) ⇒ ซ่อนไปจะแยกไม่ออกระหว่าง
 *      "ไม่มีอะไรค้าง" กับ "โหลดไม่ขึ้น"
 *
 * ⚠️ **ทำไมไม่ทำเป็น `variant` ของ `AppEmptyState`:** คอมโพเนนต์นั้นมีแกนขนาดอยู่แล้ว
 *    (`compact` boolean) การเพิ่ม `row` เข้าไปจะเกิด **สองวิธีพูดเรื่องขนาดเดียวกัน**
 *    (`compact` กับ `variant`) ซึ่งเป็นความไม่สม่ำเสมอแบบเดียวกับที่
 *    `docs/rules/frontend.md` §6 เตือนเรื่อง "สีเส้นปน 3 ค่า" · และแถวนี้ต้องรับ prop
 *    ที่ `AppEmptyState` ไม่มี (`to` + `actionLabel` จัดชิดขวา) ⇒ แยกเป็นคอมโพเนนต์กลางตัวใหม่
 *
 * ⚠️ **ไม่ครอบ `AppCard` เอง** — ให้วิวเป็นคนครอบ (เหมือนทุกบล็อกใน `Home.vue`)
 *    เพื่อให้แถวใบเดียวใช้ได้ทั้งใน/นอกการ์ด และไม่ผูกความหนาเส้นขอบไว้ที่นี่
 *
 * ⚠️ **ค่าเริ่มต้นของ `tone` คือ `neutral` ไม่ใช่ `ok`** — ข้อความส่วนใหญ่ที่มาที่นี่คือ
 *    "ยังไม่ได้ทำ X" ซึ่ง **ไม่ใช่ความสำเร็จ** ⇒ เขียวต้องเป็นค่าที่ *ขอมา* เท่านั้น
 *    (มิฉะนั้น "ยังไม่เคยแจ้งเรื่อง" จะขึ้นเครื่องหมายถูกเขียว ซึ่งอ่านผิดความหมาย)
 */
withDefaults(
  defineProps<{
    /** bootstrap-icons base name เช่น `'bi-check2-circle'` */
    icon?: string
    /** บรรทัดเดียว — บอกว่า "ว่างเพราะอะไร" (ต้องสั้นพอที่จะไม่ตัดบนจอ 360dp) */
    title: string
    /**
     * สีของไอคอน
     * - `ok` — เขียว = **ตรวจแล้วเรียบร้อย** ("ไม่มีเรื่องค้าง")
     * - `neutral` — เทา = **ยังไม่ได้ทำ** ("ยังไม่เคยแจ้งเรื่อง")
     */
    tone?: 'ok' | 'neutral'
    /** ทางออก — ไม่ส่ง = ไม่มีลิงก์ (ใช้เมื่อความว่างนั้นไม่มีอะไรให้ทำต่อ) */
    to?: RouteLocationRaw
    /** ข้อความบนลิงก์ — ต้องส่งคู่กับ `to` */
    actionLabel?: string
    /**
     * บริบทของลิงก์สำหรับโปรแกรมอ่านหน้าจอ — ต่อท้ายด้วย `sr-only`
     *
     * ⚠️ จำเป็นเมื่อ `actionLabel` เป็นคำที่อ่านเดี่ยว ๆ แล้วไม่รู้ว่าของบล็อกไหน
     *    ("คิวทั้งหมด" ของอะไร?) — ตามแบบเดียวกับ `SchoolSystemsCard.vue`
     */
    context?: string
  }>(),
  { icon: 'bi-check2-circle', tone: 'neutral' },
)
</script>

<template>
  <div class="flex min-h-11 items-center gap-3 px-4 py-2">
    <!-- ไอคอนเป็น *ตัวช่วยจำ* ไม่ใช่ตัวสื่อความหมาย — ข้อความข้าง ๆ คือตัวจริง
         (ผู้ใช้ที่ตาบอดสี/โปรแกรมอ่านหน้าจอ ได้ความหมายครบจาก `title` แล้ว) -->
    <i
      class="bi shrink-0 text-sm"
      :class="[icon, tone === 'ok' ? 'text-ok' : 'text-ink-3']"
      aria-hidden="true"
    />
    <p class="min-w-0 flex-1 truncate text-[13px] font-medium text-ink-2">{{ title }}</p>

    <!-- ลิงก์ท้ายแถวใช้ `AppButton` ไม่ใช่ `<a>` เขียนเอง — ปุ่ม "คิวทั้งหมด"/"ดูทั้งหมด"
         ที่หัวการ์ดซึ่งแถวนี้เข้าแทนที่ ใช้ตัวนี้อยู่แล้ว ⇒ รูปแบบปุ่มไม่เปลี่ยนตามการยุบ
         และ `size="sm"` ถ่าง *พื้นที่กด* ถึง 44px ด้วย `after:` อยู่แล้ว (ดู `AppButton.vue`)
         ⇒ ไม่ต้องกังวลว่าแถวจะเตี้ยจนกดไม่ถนัด -->
    <AppButton v-if="to" variant="text" size="sm" :to="to">
      {{ actionLabel }}
      <span v-if="context" class="sr-only"> — {{ context }}</span>
    </AppButton>
  </div>
</template>
