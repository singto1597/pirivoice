"""โทเคนสำหรับบัตรเช็คอินกิจกรรม (D2) — HMAC-SHA256 ไม่มี dependency ภายนอก

รูปแบบ: `PIRI-EVT1:<event_id>:<registration_id>:<sig>`

⭐ **ทำไมโทเคนต้องลงนาม ไม่ใช่ส่ง `registration_id` เปล่า ๆ**

   ทางเทคนิคแล้ว endpoint เช็คอินรับ `registration_id` ตรง ๆ ได้อยู่แล้ว (โหมดกดมือของสภา)
   ⇒ โทเคนไม่ได้เพิ่ม *อำนาจ* ให้ใคร — สิ่งที่มันเพิ่มคือ **ความน่าเชื่อถือของหลักฐาน**:
   `audit_logs` แยกออกได้จริงว่าแถวนี้เกิดจาก *"สแกนบัตรที่ระบบออกให้"* หรือ *"สภากดมือ"*
   ถ้า payload เป็นเลข id เปล่า สองอย่างนี้จะแยกกันไม่ได้เลย

   ⚠️ **สิ่งที่โทเคนนี้ *ไม่* กัน — พูดให้ตรง:** มัน**ไม่กันการเข้าแทนกัน** (เพื่อนถือสกรีนช็อต
      ของเพื่อนมาสแกน) เพราะคนที่ต้องมีสิทธิ์ `MANAGE_EVENTS` คือ **คนสแกน** ไม่ใช่คนถือบัตร
      ⇒ ด่านนั้นคือ **ตาสภาที่เห็นชื่อบนจอ** ตอนสแกน ไม่ใช่ด่านคริปโต · และมัน**ไม่กัน**
      การที่สภาตั้งใจเช็คอินให้คนที่ยังไม่มา (โหมดกดมือ — ซึ่งเป็นสิ่งที่ต้องทำได้จริง)

⭐ **ทำไม HMAC บน `SECRET_KEY` แทนการเพิ่มคอลัมน์โทเคนแบบสุ่มต่อแถว**

   | | HMAC (แบบนี้) | คอลัมน์สุ่มต่อแถว |
   |---|---|---|
   | migration | **ไม่ต้อง** (`checked_in_at` มีอยู่แล้ว) | ต้อง + backfill แถวเก่า |
   | เขียนตอนสมัคร | ไม่มี | ทุกครั้ง (INSERT/UPDATE) |
   | ทนการหมุนคีย์ | ❌ หมุน = บัตรที่พิมพ์แล้วทุกใบตาย | ✅ |
   | ยกเลิกรายใบ | ❌ | ✅ — **แต่ไม่มี UI ให้กด ⇒ ข้อดีนี้ได้จริง 0** |

   ⇒ เลือก HMAC เพราะข้อดีที่แพ้เป็นข้อดีที่**ใช้ไม่ได้จริง**ในระบบนี้ และข้อเสียที่ชนะคือ
   **งานที่หายไปทั้งก้อน** (migration + คอลัมน์ + การเขียน)

🔑 **`SECRET_KEY` ไม่ใช่ env ที่ตั้งใหม่** — `core/config.py:11` บังคับให้มีอยู่แล้วทุกที่ที่แอปบูต
   (`.env.example:24` · `docker-compose.test.yml:31`) แต่เดิม **ไม่มีโค้ดไหนใช้เลย** (`grep` = 0 ที่)
   ⇒ การเอามาใช้ที่นี่ทำให้มันกลายเป็น **load-bearing**: **ถ้าหมุน `SECRET_KEY` บัตรเช็คอิน
   ทุกใบที่พิมพ์/แชร์ไปแล้วจะใช้ไม่ได้ทันที โดยไม่มี error ให้เห็น** (สแกนแล้วขึ้น "รหัสไม่ถูกต้อง")
   ⇒ ถ้าจะหมุน ต้องยอมรับว่าต้องออกบัตรใหม่ (นักเรียนเปิดหน้าเดิมดูได้ทันที — ไม่ต้องพิมพ์ซ้ำ)

⚠️ **payload ฝัง `event_id` มาด้วยโดยเจตนา** — ปลายทางคือ `POST /events/{event_id}/check-in`
   ⇒ service เทียบ `event_id` ในโทเคนกับใน path **เสมอ**

   ⚠️ **อย่าเข้าใจว่าการเทียบนี้คือกำแพงความปลอดภัย** — มันไม่ใช่ · คิวรีฝั่ง service กรอง
      `AND r.event_id = <path>` อยู่แล้ว และ `registration_id` ชี้แถวได้แถวเดียวเสมอ
      ⇒ บัตรข้ามงานไปไม่ถึงข้อมูลของอีกงานหนึ่ง **ต่อให้ไม่เทียบก็ตาม** (พิสูจน์ด้วย mutation
      ในรอบ D2: ปิดการเทียบแล้วได้ 404 ไม่ใช่การหลุดเข้าไปเช็คอินสำเร็จ)
      · สิ่งที่การเทียบซื้อมาคือ **ข้อความที่ถูกต้อง** — 400 "รหัสนี้เป็นของกิจกรรมอื่น"
      ซึ่งบอกสภาได้ทันทีว่าเด็กหยิบบัตรผิดงาน แทน 404 ที่ชี้ว่า "ระบบหาข้อมูลไม่เจอ"
"""
import base64
import hashlib
import hmac

from core.config import settings

# เวอร์ชันของรูปแบบ payload — ขึ้นต้นด้วยค่านี้เพื่อ
#   (ก) แยกโดเมนจากการใช้ `SECRET_KEY` อื่นในอนาคต (ลายเซ็นชุดหนึ่งต้องไม่ถูกเอาไปใช้ข้ามบริบท)
#   (ข) วันที่เปลี่ยนรูปแบบ จะได้ปฏิเสธของเก่าอย่างชัดเจนแทนที่จะ parse ผิด ๆ
#
# ⚠️ **ห้ามเปลี่ยนค่านี้โดยไม่ตั้งใจ** — บัตรที่แชร์ไปแล้วจะกลายเป็น "รหัสไม่ถูกต้อง" ทั้งหมด
#    (ถ้าจำเป็นต้องเปลี่ยน ให้เปลี่ยนเป็น `PIRI-EVT2` และรองรับทั้งสองแบบช่วงเปลี่ยนผ่าน)
PREFIX = "PIRI-EVT1"

# โดเมนของลายเซ็น — ต้องไม่ซ้ำกับข้อความที่อื่นที่ลงนามด้วย `SECRET_KEY` เดียวกัน
_SIGNING_CONTEXT = "event-checkin:v1"

# ตัดเหลือ 16 ไบต์ (22 ตัวอักษร base64url) — ยาวพอกันการเดาแบบ brute force
# (2^128) แต่ทำให้ payload ทั้งก้อนสั้นพอที่ QR จะยังเป็น version ต่ำและสแกนง่ายจากจอมือถือ
_SIG_BYTES = 16

# จำนวนชิ้นเมื่อ split(":") — `PREFIX`, event_id, registration_id, sig
_PARTS = 4


def _sign(event_id: int, registration_id: int) -> str:
    """ลายเซ็นของคู่ (กิจกรรม, ใบสมัคร) — deterministic ⇒ บัตรใบเดิมได้รหัสเดิมทุกครั้ง

    ⚠️ **ไม่ใส่ timestamp/วันหมดอายุโดยเจตนา** — บัตรต้องใช้ได้จนถึงวันงาน ซึ่งอาจเป็น
       สัปดาห์ถัดจากวันที่สมัคร และการหมดอายุจะสร้างคำถามที่ตอบไม่ได้ว่า "หมดอายุแล้วทำไง"
       (สภากดมือให้อยู่ดี) ⇒ ถ้าไม่มีอะไรให้หมดอายุ ก็ไม่ต้องมีกลไกหมดอายุ
    """
    message = f"{_SIGNING_CONTEXT}:{event_id}:{registration_id}".encode()
    digest = hmac.new(settings.SECRET_KEY.encode(), message, hashlib.sha256).digest()
    return base64.urlsafe_b64encode(digest[:_SIG_BYTES]).decode().rstrip("=")


def make(event_id: int, registration_id: int) -> str:
    """สร้างข้อความที่จะเอาไปวาดเป็น QR (และโชว์เป็นข้อความสำรองได้ด้วย)"""
    return f"{PREFIX}:{event_id}:{registration_id}:{_sign(event_id, registration_id)}"


def parse(token: str) -> tuple:
    """ตรวจลายเซ็นแล้วคืน `(event_id, registration_id)` — คืน `None` ถ้าไม่ผ่าน

    ⚠️ **คืน `None` รวมทุกกรณีที่ไม่ผ่าน** (รูปแบบผิด · ตัวเลข parse ไม่ได้ · ลายเซ็นไม่ตรง)
       เจตนาเดียวกับ `safeRedirect()`: **ผู้เรียกตัดสินใจไม่ได้ว่า "ผิดแบบไหน" และไม่ควรรู้**
       ⇒ ข้อความเดียวกันหมด ⇒ ไม่มี oracle ให้ไล่เดา (เช่น "ลายเซ็นผิด" บอกว่าเลขข้างในถูก)

    ⚠️ เทียบลายเซ็นด้วย `hmac.compare_digest` **เท่านั้น** — `==` ของสตริงเป็น early-exit
       ⇒ รั่วเวลาเทียบ (timing attack) ให้คนที่ยิงซ้ำ ๆ ไล่เดาลายเซ็นทีละตัวอักษรได้
    """
    if not isinstance(token, str):
        return None
    parts = token.strip().split(":")
    if len(parts) != _PARTS or parts[0] != PREFIX:
        return None
    try:
        # `int()` เข้มอยู่แล้ว: "12x" / "" / "1.0" / " 1" ที่ strip แล้วไม่ผ่าน
        # ⚠️ ไม่รับเลขติดลบ/ศูนย์ — id ของ Postgres SERIAL เริ่มที่ 1
        event_id = int(parts[1])
        registration_id = int(parts[2])
    except ValueError:
        return None
    if event_id < 1 or registration_id < 1:
        return None
    if not hmac.compare_digest(parts[3], _sign(event_id, registration_id)):
        return None
    return event_id, registration_id
